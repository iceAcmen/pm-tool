import assert from 'node:assert/strict'
import {createHarness} from '/private/tmp/pmtool-f02-repair-gui-harness-20261023-r2.mjs'
const h=createHarness('P2DisplayRepairGuiR2'),{browser,page}=await h.connect()
let stop
try{
  assert.equal(new URL(page.url()).origin,'http://127.0.0.1:3269')
  stop=await h.record(page,'round10-reload')
  const before=await h.state(page,'round10-before-reload')
  await page.reload({waitUntil:'domcontentloaded',timeout:15000})
  await page.waitForSelector('button[aria-label="项目管理"]',{visible:true,timeout:10000})
  const shell=await page.$('.pm-shell')
  if(!shell)await page.click('button[aria-label="项目管理"]')
  await page.waitForSelector('.pm-shell',{visible:true,timeout:10000})
  const nav=await page.evaluateHandle(()=>[...document.querySelectorAll('.pm-shell button')].find(n=>n.innerText.startsWith('目标（OKR）')))
  assert(nav.asElement());await nav.asElement().click()
  await page.waitForSelector('.pm-okr-related-row',{visible:true,timeout:10000})
  const after=await h.state(page,'round10-related-after-reload')
  assert.notEqual(after.timeOrigin,before.timeOrigin)
  const tree=await page.$$eval('.pm-okr-node',nodes=>nodes.map(n=>({title:n.querySelector('.pm-okr-title')?.innerText,krs:[...n.querySelectorAll('.pm-okr-kr')].map(k=>({title:k.querySelector('.pm-okr-kr-title')?.innerText,primary:k.querySelector('.pm-okr-own-note')?.innerText,status:k.querySelector('.pm-okr-status')?.innerText,related:[...k.querySelectorAll('.pm-okr-related-row')].map(r=>r.innerText)}))})))
  await h.save('round10-related-after-reload-adjacency.json',tree)
  const tasks=await page.evaluateHandle(()=>[...document.querySelectorAll('.pm-shell button')].find(n=>n.innerText.startsWith('全部任务')))
  await tasks.asElement().click()
  await page.waitForSelector('[data-pm-row="t-0007"]',{timeout:10000})
  await(await page.$('[data-pm-row="t-0007"]')).scrollIntoView()
  await h.state(page,'round10-a-slot-after-reload')
  const a=await page.$$eval('[data-pm-row]',nodes=>nodes.map(n=>({id:n.getAttribute('data-pm-row'),slot:n.querySelector('.pm-export-slot')?.innerText,at:n.querySelector('.pm-export-slot time')?.dateTime})))
  await h.save('round10-a-slot-after-reload-rows.json',a)
  await h.textButton(page,'QA-A-fixture-F5')
  await h.textButton(page,'QA-B-fixture-F5\np-0002 · 2026-01-01')
  await page.waitForSelector('[data-pm-row="t-0002"]',{timeout:10000})
  await h.state(page,'round10-b-slot-after-reload')
  const b=await page.$$eval('[data-pm-row]',nodes=>nodes.map(n=>({id:n.getAttribute('data-pm-row'),slot:n.querySelector('.pm-export-slot')?.innerText,at:n.querySelector('.pm-export-slot time')?.dateTime})))
  await h.save('round10-b-slot-after-reload-rows.json',b)
  assert.equal(b[0].slot,'未导出');assert(a.every(n=>n.at==='2026-10-22T21:23:08.315Z'))
  await h.textButton(page,'QA-B-fixture-F5')
  await h.textButton(page,'QA-A-fixture-F5\np-0001 · 2026-01-01')
  await page.waitForSelector('[data-pm-row="t-0007"]',{timeout:10000})
  await h.state(page,'round10-final-a')
  console.log(JSON.stringify({timeOriginBefore:before.timeOrigin,timeOriginAfter:after.timeOrigin,tree,a,b}))
}catch(e){await h.save('round10-error.json',{error:String(e),stack:e.stack});await h.state(page,'round10-error-state');throw e}
finally{if(stop)await stop();await browser.disconnect()}
